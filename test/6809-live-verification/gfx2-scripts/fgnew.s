e fgnew
 DIM p:INTEGER
 OPEN #p,"/w6":WRITE
 PRINT "A"
 RUN GFX2(p,"DWSET",6,0,0,40,24,0,1,1)
 PRINT "B"
 RUN GFX2(p,"COLOR",2)
 RUN GFX2(p,"BAR",10,10,42,18)
 RUN GFX2(p,"DEFBUFF",1,3,200)
 PRINT "C"
 RUN GFX2(p,"GET",1,3,10,10,32,8)
 PRINT "D"
 RUN GFX2(p,"PATTERN",1,3)
 PRINT "E"
 RUN GFX2(p,"PATTERN",0,0)
 PRINT "F"
 RUN GFX2(p,"OWSET",1,2,2,10,5,2,3)
 PRINT "G"
 RUN GFX2("OWEND")
 PRINT "H"
 SHELL "MERGE SYS/Stdfonts >>/nil"
 RUN GFX2(p,"FONT",200,1)
 PRINT "I"
 CLOSE #p
 PRINT "J"
q
run fgnew
bye
