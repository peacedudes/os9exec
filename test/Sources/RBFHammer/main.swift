//
//  The soak/gate CLI. Runs the hammer scenarios in a parallel pool -- once as a
//  fast gate, or for many iterations as a soak -- and verifies each run's file
//  content AND the device's structural health (dcheck/free). Exits non-zero if
//  any run comes back wrong, so it drops straight into a Makefile or CI.
//
//      swift run RBFHammer --target 68k --gate
//      swift run RBFHammer --target 68k --iterations 50 --jobs 4
//      swift run RBFHammer --target 6809 --iterations 5 --jobs 2
//
//  A soak exists to catch what a single run hides: an intermittent lost update,
//  a structural fault that only appears under contention or host load. Running
//  the contended scenarios over and over, several at once, is how those surface.
//
//  Generated by Claude Opus 4.8 (Anthropic) — collaborator: rdoggett
//  date: 07-21-2026
