import Foundation

// ── Configuration ─────────────────────────────────────────────────────────────

let repoRoot = URL(fileURLWithPath: #filePath)
    .deletingLastPathComponent()   // OS9Tests/
    .deletingLastPathComponent()   // Sources/
    .deletingLastPathComponent()   // test/
    .deletingLastPathComponent()   // repo root

let execURL  = repoRoot.appendingPathComponent("os9exec")

// Primary test disk: the repo-root h0 (SDK toolchain) dir, mounted as /dd.
// Same h0 the emulator itself already uses -- no test/-local symlink needed.
let diskPath = repoRoot.appendingPathComponent("h0").path

// Per-run scratch device, mounted as /h5: every fixture this suite creates
// lives here, never on the system disk. h0 IS the OS-9 system image -- the SDK
// toolchain, DEFS, LIB, startup -- and it used to double as scratch, so two
// sessions running the suite at once deleted each other's fixed-name fixtures
// (t_text and friends) out of it mid-run. The failures that produced were
// indistinguishable from real regressions and cost a full debugging session
// before the shared symlink was spotted. A directory private to this process
// removes the collision by construction, and keeps the system disk read-only
// in practice. Devices map to host dirs via OS9Hx -- see filestuff.c.
let scratchDev  = "h5"
let scratchDisk = URL(fileURLWithPath: NSTemporaryDirectory())
    .appendingPathComponent("os9test-scratch-\(ProcessInfo.processInfo.processIdentifier)").path
let scratch     = "/\(scratchDev)"

// Created before the first os9exec starts; a stale one from a killed run is
// cleared first so fixtures never survive into a later run.
try? FileManager.default.removeItem(atPath: scratchDisk)
try? FileManager.default.createDirectory(atPath: scratchDisk,
                                         withIntermediateDirectories: true)
// Inside OS-9 the boot disk is /dd; the ONE thing /h0 is for is proving the
// default device naming still resolves. That default is "startPath/<dev>" --
// the emulator's working directory, which is this scratch -- so h0 is linked
// here rather than forced with OS9H0. An explicit override would test the
// override, not the default, and the alias would stop meaning anything.
try? FileManager.default.createSymbolicLink(atPath: scratchDisk + "/h0",
                                            withDestinationPath: diskPath)

// The confinement canary: a file in the device root's HOST PARENT, holding a
// secret string that must NEVER become readable from inside OS-9 by any path
// trick (see the "fs: confine" tests). Declared and planted up here, not down
// beside those tests, because container mode has to MOUNT it -- every os9()
// invocation builds its mount list, so the path must exist before the first one.
let canaryName   = "FSCANARY_\(UUID().uuidString.prefix(8))"
let canaryHost   = URL(fileURLWithPath: diskPath).deletingLastPathComponent()
                      .appendingPathComponent(canaryName).path
let canarySecret = "CANARYLEAK_\(UUID().uuidString.prefix(8))"
try? (canarySecret + "\r").write(toFile: canaryHost, atomically: true, encoding: .utf8)

// Optional container image for testing
// Docker: DOCKER_IMAGE=os9exec:latest swift run
// Apple Container: CONTAINER_IMAGE=os9exec:apple swift run
let dockerImage = ProcessInfo.processInfo.environment["DOCKER_IMAGE"]
let containerImage = ProcessInfo.processInfo.environment["CONTAINER_IMAGE"]

// Shell binary to launch — override with OS9SHELL env var if shell is not in /dd/CMDS
// e.g.: OS9SHELL=/h0/CMDS/shell make test
let shellArg = ProcessInfo.processInfo.environment["OS9SHELL"] ?? "shell"

// Command directory of the SDK disk these tests exercise. The tests chx here
// so every command — and every command a command forks internally (e.g.
// deldir → pd) — resolves from the SDK disk, with no other SHARE fallbacks
// shadowing it. /dd is h0 itself (see diskPath above), so this is just
// /dd/CMDS: override with OS9_SDK_CMDS if your command set is mounted elsewhere.
let sdkCmds = ProcessInfo.processInfo.environment["OS9_SDK_CMDS"] ?? "/dd/CMDS"

// ── Shell runner ──────────────────────────────────────────────────────────────

/// Run one or more OS-9 shell commands and return combined stdout.
/// ESC on a final line signals EOF to the shell.
/// Times out after `timeout` seconds to prevent hangs from blocking the suite.
/// If DOCKER_IMAGE is set, runs via Docker; otherwise runs locally (assumes dd symlink exists).
/// True when tests run inside a container (Docker or Apple Container) rather than
/// against the locally built binary.
let containerized = dockerImage != nil || containerImage != nil

/// Per-command budget. A container pays for image start-up and a cold emulator
/// boot (the UAE CPU tables are rebuilt every run) on top of the command itself,
/// which pushed the slower commands (list, pr, tar, build...) past the native 15s
/// and made them report "(timeout)" as if they had failed. Give containers room.
let defaultTimeout: TimeInterval = containerized ? 45 : 15

/// Stop a container by name. On timeout we MUST do this: terminating the `docker
/// run` client does not stop the container it started -- the container keeps
/// running, keeps the pipes open, and the suite hangs forever instead of
/// reporting a timeout. (Seen for real: one container left "Up 18 minutes" with
/// the whole run wedged behind it.)
func killContainer(_ name: String) {
    let runtime = dockerImage != nil ? "docker" : "container"
    let kill = Process()
    kill.executableURL = URL(fileURLWithPath: "/usr/bin/env")
    kill.arguments     = [runtime, "kill", name]
    kill.standardOutput = FileHandle.nullDevice
    kill.standardError  = FileHandle.nullDevice
    try? kill.run()
    kill.waitUntilExit()
}

// `flags` adds emulator flags for ONE call, which OS9_FLAGS (whole-run, read
// from the parent's environment) cannot express. Applied to both the local and
// the containerized argument lists, so a test using it still runs in a container.
func os9(_ commands: [String], timeout: TimeInterval = defaultTimeout, paced: Bool = false,
         disk: String = diskPath, env: [String: String] = [:],
         flags: [String] = [], holdOpen: TimeInterval = 0) -> String {
    let setup  = "chx \(sdkCmds)\nload math cio\n"
    // ESC then Ctrl-D: EOF is a per-path setting, not a constant. A site whose
    // `.login` runs `tmode eof=04` (a normal thing to do -- it matches Unix)
    // makes EOF Ctrl-D, and because tmode acts on the PATH the change outlives
    // the login shell. A harness that sent only ESC would then sit at a live
    // prompt until it timed out, looking like a hang in whatever it last ran.
    // Sending both costs one stray line in whichever mode is not in force.
    // One write, not two: after the emulator acts on the first terminator it is
    // gone, and a follow-up write to the closed pipe would raise EPIPE here.
    let body       = setup + commands.joined(separator: "\n") + "\n"
    let terminator = "\u{1B}\n\u{04}\n"
    // holdOpen delays ONLY the terminator. A test that acts on the running
    // system from outside (writing to a bound pty, say) needs OS-9 processes to
    // still be alive when it acts; send the terminator immediately and the shell
    // can exit first, leaving the emulator in baud_drain_all_pending where
    // nothing is scheduled any more. A check written against that state passes
    // whatever the emulator does.
    let input  = holdOpen > 0 ? body : body + terminator

    let process = Process()
    // The system tick is on by default in the emulator, so the suite runs
    // pre-empted -- the configuration users actually get.
    //
    // OS9_FLAGS passes arbitrary emulator flags through, rather than growing a
    // bespoke env var per flag (there used to be one just for the tick, which
    // nobody but its author knew existed). `make test-notick` uses it to run
    // the whole suite with the clock off, guarding the "-q" fallback.
    let extraFlags = (ProcessInfo.processInfo.environment["OS9_FLAGS"] ?? "")
        .split(separator: " ").map(String.init)
    let speedFlag: [String] = (paced ? [] : ["-r"]) + extraFlags + flags
    // Named so a timeout can actually stop it -- see killContainer above.
    let containerName = "os9test-\(UUID().uuidString.prefix(8))"

    // `mount -k` writes its scratch image relative to the emulator's WORKING
    // DIRECTORY -- it ignores OS9Hx, verified directly -- and every image
    // cleanup below deletes scratchDisk/<dev>. Both point at the per-run
    // scratch so they cannot disagree: cwd used to be repoRoot, which put the
    // images in the worktree where two runs from the same checkout overwrote
    // each other's, and left h8/h9/ha/hb/hc lying about after a killed run.
    process.currentDirectoryURL = URL(fileURLWithPath: scratchDisk)

    // `currentDirectoryURL` above only sets the cwd of the *client* process. In
    // container mode that client is `docker`/`container`, so it says nothing
    // about where os9exec runs INSIDE the container -- there the cwd is the
    // image's `WORKDIR /work`, which is container-local and dies with `--rm`.
    // That is why the several `fs: permission` tests that share one `mount -k`
    // device used to break in container mode while working locally: the image
    // landed in /work and vanished between tests, and any test asserting
    // `contains "Error #"` then PASSED for the wrong reason, because a missing
    // device errors too. `-w` puts the container's cwd on the bind-mounted
    // scratch so `mount -k` images persist across the per-test containers,
    // exactly as they do locally.
    //
    // Pointing the cwd at a bind mount used to fail with
    // `mount -k: can't create '/?/h9'` (E_BPNAM) -- that was StartDir()
    // rebuilding the cwd by matching st_ino against d_ino, which legitimately
    // differ at a mount point. Fixed in 5c662ca (getcwd), so this is safe now.
    // Not "/" either, which would collide with the OS-9 device namespace (see
    // the WORKDIR comment in docker/Dockerfile).
    //
    // Two further mounts exist so the fs self-tests are not vacuous in a
    // container. Both were measured, not assumed (2026-07-25):
    //
    //  * diskPath at its OWN host path. `/h0` resolves by the DEFAULT rule --
    //    startPath/h0, i.e. the symlink planted in the scratch dir, which
    //    points at the host's diskPath. Without this the symlink dangles
    //    inside the container and `dir /h0` gives E_MNF, so the "/h0 device
    //    alias" resolution test could never run there. Always diskPath, never
    //    `disk`: the local symlink points at diskPath whatever /dd is
    //    overridden to, and /h0 must keep meaning the same thing.
    //  * the canary at BOTH places an escape could land: the container's "/",
    //    which is genuinely /dd's parent there (/dd is a literal absolute host
    //    path when OS9DISK is unset), and its own host path, which is what
    //    `/h0/..` reaches (since /h0 resolves through the symlink to diskPath).
    //    Without these the escape spellings name a file that does not exist, so
    //    a confinement test would PASS on the absence of the target rather than
    //    on the emulator refusing to escape -- the exact false-pass shape this
    //    suite has already been bitten by. Both were confirmed load-bearing by
    //    making the secret reachable and watching the assertions fail.
    let containerRunArgs = [
        "--rm",
        "-i",
        "--name", containerName,
        "-v", disk + ":/dd",
        "-v", diskPath + ":" + diskPath,
        "-v", canaryHost + ":/" + canaryName,
        "-v", canaryHost + ":" + canaryHost,
        "-v", scratchDisk + ":" + scratch,
        "-w", scratch,
        "-e", "OS9H\(scratchDev.dropFirst())=" + scratch,
    ]

    if let image = dockerImage {
        // Run via Docker: mount local dd directory and pipe stdin/stdout
        process.executableURL = URL(fileURLWithPath: "/usr/bin/env")
        process.arguments = ["docker", "run"] + containerRunArgs + [image] + speedFlag + ["shell"]
    } else if let image = containerImage {
        // Run via Apple Container: mount local dd directory and pipe stdin/stdout
        process.executableURL = URL(fileURLWithPath: "/usr/bin/env")
        process.arguments = ["container", "run"] + containerRunArgs + [image] + speedFlag + ["shell"]
    } else {
        // Run locally: OS9DISK points straight at the repo-root h0 dir.
        process.executableURL = execURL
        process.arguments    = speedFlag + [shellArg]
        // OS9H5 gets the PHYSICALLY RESOLVED scratch path, not scratchDisk's own
        // spelling. On macOS NSTemporaryDirectory() is /var/folders/... while the
        // emulator computes its startPath (and thus every `mount -k` device root)
        // as /private/var/folders/... -- the same directory behind a firmlink.
        // FindConfiguredDeviceRoot compares root strings LITERALLY (deliberately
        // -- see its own comment), so those two spellings never match each other,
        // and h5 silently stopped being recognised as the enclosing root of a
        // device mounted inside it. That made the nested-device-root tests below
        // pass no matter what the emulator did: the outer root was invisible, so
        // the very overlap they exist to test never existed. Resolving here makes
        // both roots share one spelling, exactly as they already do under a
        // container (where the scratch is bind-mounted at a plain /h5).
        let resolvedScratchDisk: String = {
            guard let r = realpath(scratchDisk, nil) else { return scratchDisk }
            defer { free(r) }
            return String(cString: r)
        }()
        process.environment  = ["OS9DISK": disk,
                                "OS9H\(scratchDev.dropFirst())": resolvedScratchDisk]
                               .merging(env) { _, caller in caller }
    }

    let stdinPipe  = Pipe()
    let stdoutPipe = Pipe()
    let stderrPipe = Pipe()  // Capture stderr too for debugging
    process.standardInput  = stdinPipe
    process.standardOutput = stdoutPipe
    process.standardError  = stderrPipe

    guard (try? process.run()) != nil else { return "" }
    stdinPipe.fileHandleForWriting.write(Data(input.utf8))
    if holdOpen > 0 {
        DispatchQueue.global().async {
            Thread.sleep(forTimeInterval: holdOpen)
            // The emulator may already have exited (a test can abort the very
            // shell we are talking to), so a write here can EPIPE. Ignore it:
            // the run is over either way.
            signal(SIGPIPE, SIG_IGN)
            try? stdinPipe.fileHandleForWriting.write(contentsOf: Data(terminator.utf8))
            try? stdinPipe.fileHandleForWriting.close()
        }
    } else {
        stdinPipe.fileHandleForWriting.closeFile()
    }

    var output = ""
    // Read stdout and stderr concurrently to avoid deadlock
    let readGroup = DispatchGroup()

    readGroup.enter()
    DispatchQueue.global().async {
        output = String(
            decoding: stdoutPipe.fileHandleForReading.readDataToEndOfFile(),
            as: UTF8.self
        )
        readGroup.leave()
    }

    readGroup.enter()
    DispatchQueue.global().async {
        _ = stderrPipe.fileHandleForReading.readDataToEndOfFile()
        readGroup.leave()
    }

    if readGroup.wait(timeout: .now() + timeout) == .timedOut {
        if containerized { killContainer(containerName) } // client != container
        process.terminate()
        process.waitUntilExit()
        return "(timeout)"
    }
    process.waitUntilExit()

    // Ensure process is fully cleaned up before returning
    // This is critical for shared systems to prevent resource leaks
    while process.isRunning {
        Thread.sleep(forTimeInterval: 0.01)  // 10ms
    }

    return output
}

// ── Test runner ───────────────────────────────────────────────────────────────

var passed = 0
var failed = 0
let filter = CommandLine.arguments.dropFirst().first ?? ""

func run(_ name: String, expectation: String, commands: [String], disk: String = diskPath,
         timeout: TimeInterval = defaultTimeout, env: [String: String] = [:],
         check: (String) -> Bool) {
    guard filter.isEmpty || name.localizedCaseInsensitiveContains(filter) else { return }
    let output = os9(commands, timeout: timeout, disk: disk, env: env)
    if check(output) {
        print("PASS: \(name)")
        passed += 1
    } else {
        print("FAIL: \(name)")
        print("      [\(expectation)]")
        let preview = output
            .split(separator: "\n")
            .filter { !$0.hasPrefix("#") && $0 != "$" && !$0.isEmpty }
            .prefix(4)
            .joined(separator: " | ")
        print("      output: \(preview)")
        if ProcessInfo.processInfo.environment["OS9_DUMPFAIL"] != nil {
            print("      ---- full output (\(output.count) chars) ----")
            print(output)
            print("      ---- end ----")
        }
        failed += 1
    }
}

func check(_ name: String, contains pattern: String, _ commands: String...) {
    run(name, expectation: "contains: \(pattern)", commands: commands) { $0.contains(pattern) }
}

func check(_ name: String, contains pattern: String, disk: String, _ commands: String...) {
    run(name, expectation: "contains: \(pattern)", commands: commands, disk: disk) {
        $0.contains(pattern)
    }
}

func check(_ name: String, absent pattern: String, _ commands: String...) {
    run(name, expectation: "absent: \(pattern)", commands: commands) { !$0.contains(pattern) }
}

func noError(_ name: String, _ commands: String...) {
    // Match "Error #" — the OS-9 error format — not the startup ioctl message
    run(name, expectation: "no OS-9 error", commands: commands) {
        !$0.contains("Error #")
    }
}

func checkEnv(_ name: String, contains pattern: String,
              env: [String: String], _ commands: String...) {
    run(name, expectation: "contains: \(pattern)", commands: commands, env: env) {
        $0.contains(pattern)
    }
}

