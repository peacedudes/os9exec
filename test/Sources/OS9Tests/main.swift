// ══════════════════════════════════════════════════════════════════════════════
// FILESYSTEM SELF-TESTS   (name prefix "fs:" — run just these with
//   swift run --package-path test OS9Tests fs:)
// ══════════════════════════════════════════════════════════════════════════════
// Two mental categories of test live in this file:
//   1. COMMAND SMOKE TESTS (everything above) — "does `grep` / `tar` / `dsave`
//      run and produce plausible output" — they depend on which command modules
//      we happen to have working.
//   2. SELF-TESTS (this section, plus the RBF/ramdisk/baud ones above) — they
//      test the emulator's OWN guaranteed behavior, provision everything they
//      need, and assert exact outcomes. Anyone can run them; nothing external
//      is assumed.
// These verify the file system itself: that every legal spelling of a path
// resolves to the SAME right place, that NO path trick escapes a host-native
// device root into the host OS (the confinement the emulator must guarantee —
// see the '..'-past-root regression, git log), and that OS-9 permissions are
// honored on an RBF image. These run in container mode too: the canary is
// mounted at the container's "/" (which really is /dd's parent there) and the
// disk at its own host path so the /h0 symlink resolves -- see containerRunArgs.
do {
    // Per-run name, for the same reason the fixtures moved to /h5: this dir
    // lives inside the SHARED system disk (it must -- these tests assert on the
    // /dd and /h0 spellings themselves, so they cannot move to a scratch
    // device), and the suite DELETES it when done. Two sessions with the same
    // name deleted it out from under each other. The suffix is digits so both
    // the lower- and UPPER-case spellings below stay valid.
    let fsRun        = String(ProcessInfo.processInfo.processIdentifier)
    let fsHostDir    = diskPath + "/USR/CLAUDE/fsselftest\(fsRun)"   // under /dd, host-visible
    let fsSubHost    = fsHostDir + "/SUB"
    let marker       = "FSMARK_\(UUID().uuidString.prefix(8))"
    // The canary itself (in the device root's host parent) is planted up in the
    // configuration section -- container mode must mount it, which happens
    // before any test runs. Here we only add the fixtures that live inside the
    // device.

    // provision on the host (deterministic; OS-9 files use CR line endings)
    try? FileManager.default.createDirectory(atPath: fsSubHost, withIntermediateDirectories: true)
    try? (marker + "\r").write(toFile: fsSubHost + "/deep", atomically: true, encoding: .utf8)
    // a host symlink INSIDE the device pointing OUT at the canary — the realpath
    // confinement must refuse to follow it out of the device root. The host path
    // works verbatim in container mode too, because the canary is mounted there
    // under its own name; a dangling link would make this pass on a broken
    // symlink rather than on confinement.
    try? FileManager.default.createSymbolicLink(atPath: fsSubHost + "/esclink",
                                                withDestinationPath: canaryHost)

    // guard: the whole confinement half is vacuous if the canary wasn't written
    if (try? String(contentsOfFile: canaryHost, encoding: .utf8))?.contains(canarySecret) != true {
        print("FAIL: fs: setup — canary file not planted"); failed += 1
    }

    let sub = "/dd/USR/CLAUDE/fsselftest\(fsRun)/SUB"   // OS-9 working dir for these

    // ---- resolution: every legal spelling must read the SAME marker file ----
    // (the marker tests double as the positive control for the confinement
    //  tests below: they prove `list` really does surface a file's contents.)
    func resolves(_ label: String, _ spelling: String) {
        run("fs: resolve \(label)", expectation: "reads the marker via '\(spelling)'",
            commands: ["chd \(sub)", "list \(spelling)"]) { $0.contains(marker) }
    }
    resolves("relative",              "deep")
    resolves("dot-relative",          "./deep")
    resolves("absolute /dd",          "/dd/USR/CLAUDE/fsselftest\(fsRun)/SUB/deep")
    resolves("/h0 device alias",      "/h0/USR/CLAUDE/fsselftest\(fsRun)/SUB/deep")
    resolves("double slash",          "/dd//USR/CLAUDE/fsselftest\(fsRun)/SUB/deep")
    resolves("embedded /./",          "/dd/./USR/CLAUDE/fsselftest\(fsRun)/SUB/deep")
    resolves("parent round-trip",     "../SUB/deep")
    resolves("through SYS and back",  "/dd/SYS/../USR/CLAUDE/fsselftest\(fsRun)/SUB/deep")
    resolves("case-insensitive",      "/dd/usr/claude/FSSELFTEST\(fsRun)/sub/DEEP")
    resolves("multi-dot to root",     "...../USR/CLAUDE/fsselftest\(fsRun)/SUB/deep")       // up-4 == /dd, then descend
    resolves("over-walk clamps+keeps","............/USR/CLAUDE/fsselftest\(fsRun)/SUB/deep") // '..' past root: clamp, keep tail (regression guard)

    // ---- confinement: the host canary outside the root must be UNREACHABLE ----
    func blocked(_ label: String, _ spelling: String) {
        run("fs: confine \(label)", expectation: "canary NOT leaked via '\(spelling)'",
            commands: ["chd \(sub)", "list \(spelling)"]) { !$0.contains(canarySecret) }
    }
    blocked("/dd/../canary",        "/dd/../\(canaryName)")
    blocked("/dd/../../canary",     "/dd/../../\(canaryName)")
    blocked("deep ../ escape",      "../../../../../\(canaryName)")
    blocked("over-walk escape",     "............/\(canaryName)")
    blocked("through SYS escape",   "/dd/SYS/../../\(canaryName)")
    blocked("/h0 alias escape",     "/h0/../\(canaryName)")
    blocked("symlink out of device","esclink")            // realpath confinement must not follow it out

    try? FileManager.default.removeItem(atPath: fsHostDir)
    // canaryHost is removed in the epilogue, not here -- see the note there.

    // ---- nested device roots: '..' must stop at the INNERMOST root ----
    // The scratch device's host dir is also the emulator's working directory,
    // so `mount -k=0 he` plants a second device root INSIDE the first one --
    // /he's host path is <h5's host root>/he. OS-9 semantics: extra ".."s at a
    // device root are no-ops, so nothing under /he may reach h5's own files.
    // Before the fix, AdjustPath asked which configured root a path started in
    // and got back the FIRST prefix match in scan order (dd, h0-h9, ha-hz),
    // which for a path under /he is the ENCLOSING h5 -- so the clamp compared
    // against the wrong root and let '..' walk out. It now takes the longest
    // (innermost) match. Guarded as a leak test, not a "does it error" test:
    // asserting on the parent's CONTENT means a future regression has to
    // actually surface h5's file to fail this, and the E_PNNF spelling is free
    // to change.
    let nestSecret = "NESTMARK_\(UUID().uuidString.prefix(8))"
    let nestFile   = "nestparent\(fsRun)"
    try? (nestSecret + "\r").write(toFile: scratchDisk + "/" + nestFile,
                                   atomically: true, encoding: .utf8)

    // Positive control FIRST: the file has to be readable through h5 itself,
    // or both leak tests below pass on its absence -- the exact false-pass
    // shape the canary guard above exists to prevent.
    run("fs: nested roots — parent file IS readable from the outer device",
        expectation: "control: h5's own file reads normally via /h5",
        commands: ["chd \(scratch)", "list \(nestFile)"]) { $0.contains(nestSecret) }

    run("fs: nested roots — '..' from the inner device cannot read the outer one",
        expectation: "list ../\(nestFile) from /he must not surface h5's file",
        commands: ["mount -k=0 he", "chd /he",
                   "list ../\(nestFile)"]) { !$0.contains(nestSecret) }

    run("fs: nested roots — 'dir ..' from the inner device stays inside it",
        expectation: "dir .. from /he must not list h5's root",
        commands: ["mount -k=0 he", "chd /he",
                   "dir .."]) { !$0.contains(nestFile) }

    try? FileManager.default.removeItem(atPath: scratchDisk + "/" + nestFile)
    try? FileManager.default.removeItem(atPath: scratchDisk + "/he")

    // ---- host-native devices: attr round-trip only, NOT permission enforcement ----
    // A host directory cannot carry OS-9 ownership and attributes faithfully --
    // that is what an RBF image is for, and the "fs: permission" tests above own
    // that subject. So this asserts only what a host-native device can honestly
    // promise: attr sets the bits and reads them back, and clearing every bit
    // does not cost attr its own access (its F$Open requests neither read nor
    // write -- mode==0, it just needs a path number for the GetStat/SetStat --
    // so it can always grant access back, mirroring RBF's has_open_perm()).
    // Deliberately no assertion that the HOST refused a read: it is unfalsifiable
    // on a Docker bind mount, which fakes ownership to match whatever uid asks
    // and ignores the mode outright (measured 2026-07-25; project memory
    // docker-macos-bindmount-ignores-permissions).
    // Every bit cleared reads back as every bit cleared. This asserted
    // "--e--e--" until 2026-07-25, which was the old forced-execute mapping
    // showing through: `e` was the one attribute a host mount could not
    // round-trip, so the test was documenting the bug.
