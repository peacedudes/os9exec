// -- baud_drain_due destination crossover ------------------------------------
// baud_drain_due (consio.c) drains every paced device's FIFO from the
// scheduler, not from an fmgr entry point -- there is no ambient
// gConsoleID for it to inherit the way pConsIn/pConsInLn/ConsoleOut/pCready/
// pCclose do (see docs/superpowers/plans/2026-07-29-conspuctto-explicit-
// destination.md, "Why, precisely"). Two devices with live backlogs at once
// is exactly the shape that could leak one device's bytes onto the other's
// pty if the drain used ConsPutc's ambient gConsoleID instead of naming its
// destination explicitly.
//
// Markers: "bootptest" (unique to /dd/CMDS -- confirmed absent from the
// /dd/DEFS listing) and "flexdef.h" (unique to /dd/DEFS -- confirmed absent
// from the /dd/CMDS listing), checked live against the actual h0 disk this
// suite runs against, 2026-07-29. Neither string appears anywhere in the
// command text sent below, so a match cannot come from the shell's own
// command echo.
let dualDeviceName = "hostterm: paced output from two devices does not cross over"
let runDualDevice   = filter.isEmpty || dualDeviceName.localizedCaseInsensitiveContains(filter)

if runDualDevice {
    if let (master1, slave1, slave1Name) = makePTY(),
       let (master2, slave2, slave2Name) = makePTY() {
        let collector1 = BackpressureCollector()
        let collector2 = BackpressureCollector()
        let stopped1   = DispatchSemaphore(value: 0)
        let stopped2   = DispatchSemaphore(value: 0)

        // Both threads must be draining BEFORE the shell command starts:
        // pacing keeps both backlogs alive for ~1.7s (dir /dd/CMDS is ~3226
        // bytes at the default 19200), well past the 1024-byte pty queue, so
        // an undrained window here would deadlock the writer rather than
        // exercise the drain's device attribution.
        _ = startDrainThread(master1, collector1, stopped1)
        _ = startDrainThread(master2, collector2, stopped2)

        // Two devices, two concurrent writers, distinct content, PACED (no
        // -r) so both FIFOs are still draining across many baud_drain_due
        // calls at once.
        _ = os9(["dir /dd/CMDS >/t1 &", "dir /dd/DEFS >/t2"],
                timeout: 120, paced: true,
                env: ["OS9T1": slave1Name, "OS9T2": slave2Name])

        // The backgrounded /t1 job can still be draining its FIFO after the
        // foreground /t2 command (and the shell that spawned both) has
        // exited -- give it a moment before stopping the readers.
        usleep(500_000)
        collector1.requestStop(); collector2.requestStop()
        stopped1.wait(); stopped2.wait()
        close(master1); close(slave1)
        close(master2); close(slave2)

        let text1 = String(decoding: collector1.snapshot(), as: UTF8.self)
        let text2 = String(decoding: collector2.snapshot(), as: UTF8.self)

        let noCrossover = text1.contains("bootptest") && !text1.contains("flexdef.h")
                        && text2.contains("flexdef.h") && !text2.contains("bootptest")

        if noCrossover {
            print("PASS: \(dualDeviceName)"); passed += 1
        } else {
            print("FAIL: \(dualDeviceName)")
            print("      [expected /t1 to carry only the CMDS listing (bootptest) and")
            print("       /t2 only the DEFS listing (flexdef.h), with no crossover]")
            print("      /t1 has bootptest: \(text1.contains("bootptest")), " +
                  "/t1 has flexdef.h: \(text1.contains("flexdef.h"))")
            print("      /t2 has flexdef.h: \(text2.contains("flexdef.h")), " +
                  "/t2 has bootptest: \(text2.contains("bootptest"))")
            failed += 1
        }
    } else {
        print("FAIL: hostterm: could not create two pty pairs for the crossover test")
        failed += 1
    }
}

// -- an abort key typed on /tN interrupts THAT terminal's writer --------------
// KeyToBuffer takes its signal target from the device's own syspath
// (`lastwritten_pid`), and only lw_pid() sets it -- which ConsPutcTo reached on
// the main-console arm alone, because the hostterm_bound() branch returns first.
// So Ctrl-E typed on a bound /t1 used to flush that terminal's paced backlog
// (silently discarding queued output) while signalling nobody, and the process
// it was aimed at ran to completion. Measured, not reasoned: 3226 bytes with no
// abort, ~2984 with one -- ~240 bytes gone, listing still complete.
//
// The abort char goes to the pty MASTER, i.e. in on /t1's own input, which is
// the whole point: this is not the console's abort key. holdOpen keeps the shell
// alive past the injection, so the writer is genuinely running when it lands --
// without it the shell exits first and the FIFO flush truncates the output no
// matter what the emulator does, which passes for the wrong reason.
// Confirmed 3/3 FAIL before the fix, 0/3 after.
let tnAbortName = "hostterm: an abort key on /tN interrupts that terminal's writer"
let runTNAbort  = filter.isEmpty || tnAbortName.localizedCaseInsensitiveContains(filter)

if runTNAbort {
    if let (master, slave, slaveName) = makePTY() {
        let collector = BackpressureCollector()
        let stopped   = DispatchSemaphore(value: 0)
        _ = startDrainThread(master, collector, stopped)

        // Ctrl-E (the default PD_QUT) once a paced backlog exists but long
        // before the ~3226-byte listing could finish on its own.
        DispatchQueue.global().async {
            Thread.sleep(forTimeInterval: 0.6)
            var abortChar: UInt8 = 0x05
            _ = write(master, &abortChar, 1)
        }

        _ = os9(["dir /dd/CMDS >/t1 &", "free /dd"],
                timeout: 120, paced: true,
                env: ["OS9T1": slaveName], holdOpen: 3.0)

        usleep(500_000)
        collector.requestStop(); stopped.wait()
        close(master); close(slave)

        let text = String(decoding: collector.snapshot(), as: UTF8.self)
        // Started (first name present) but was cut off (last name absent).
        // Both halves matter: without the first, "aborted" is indistinguishable
        // from "never ran".
        let started  = text.contains("BOOTOBJS")
        let finished = text.contains("xmode")

        if started && !finished {
            print("PASS: \(tnAbortName)"); passed += 1
        } else {
            print("FAIL: \(tnAbortName)")
            print("      [expected the listing to start (BOOTOBJS) and be cut off")
            print("       before its last entry (xmode)]")
            print("      started: \(started), ran to completion: \(finished), " +
                  "bytes: \(collector.snapshot().count)")
            failed += 1
        }
    } else {
        print("FAIL: hostterm: could not create a pty for the /tN abort test")
        failed += 1
    }
}

// -- -d 0x0002 return lines name the call that was entered --------------------
// funcdispatch.c used to re-derive a return line's name from cp->func at exit
// time. That field is a single slot per process, overloaded three ways
// (function code, exception vector offset, and 0 for "fatal, no handler"), so
// by the time a return printed it could hold something else entirely -- and
// because F$Link IS function code $00, the 0 sentinel printed a whole
// fabricated `<<< F$Link returns:` line, padded with the 0xAAAAAAAx register
// fill pattern as though those values meant something. That is not cosmetic:
// it sent a 2026-07-29 investigation chasing an E_NOTRDY attributed to the
// wrong call. debug_comein now snapshots what it announced.
//
// The BACKGROUNDED job is load-bearing, not decoration. exec_syscall skips its
// own debug_return whenever arbitration is due and re-enters the main loop
// instead, whose top prints a return for whatever cp->func now holds -- so the
// defect needs a second runnable process for arbitration to fall due while an
// internal utility (`procs` here) is mid-run. `&` guarantees that structurally.
//
// Measured against the pre-fix binary, because two tidier-looking versions of
// this test were VACUOUS: bare `procs` passed, and so did bare `free /dd`, even
// though `free /dd` does reproduce when piped in outside this harness. Timing
// alone is not a reliable trigger. This shape failed 3/3 before the fix and
// passes 3/3 after. Do not simplify the command list without re-checking that
// it can still fail.
let tracePairingName = "debug: -d syscall trace pairs every return with its entry"
let runTracePairing  = filter.isEmpty || tracePairingName.localizedCaseInsensitiveContains(filter)

if runTracePairing {
    let trace = os9(["dir /dd/DEFS &", "procs"], flags: ["-d", "0x0002"])

    // ">>>" / "<<<" then one mask char, then "Pid=NN: OS9 <name>". START and
    // INTERCEPT are legitimately unpaired: neither has an entry line of its own.
    var pending: [String: [String]] = [:]
    var unpaired: [(String, String)] = []
    var mismatched: [(String, String, String)] = []

    for line in trace.split(whereSeparator: \.isNewline) {
        for match in line.ranges(of: try! Regex("(>>>|<<<).Pid=([0-9]+): OS9 ([^ ]+)")) {
            let field = String(line[match])
            let isEntry = field.hasPrefix(">>>")
            // "…Pid=NN: OS9 name" -- split off the pid and the name positionally.
            guard let pidPart  = field.split(separator: "=").last?.split(separator: ":").first,
                  let namePart = field.split(separator: " ").last else { continue }
            let pid  = String(pidPart)
            let name = String(namePart)
            if name == "START" || name == "INTERCEPT" { continue }

            if isEntry {
                pending[pid, default: []].append(name)
            } else if let expected = pending[pid]?.popLast() {
                if expected != name { mismatched.append((pid, expected, name)) }
            } else {
                unpaired.append((pid, name))
            }
        }
    }

    // F$Exit never returns, so it is expected to stay open; nothing else should.
    let strayOpen = pending.flatMap { pid, names in
        names.filter { $0 != "F$Exit" }.map { (pid, $0) }
    }

    if trace.contains("Pid=") && unpaired.isEmpty && mismatched.isEmpty && strayOpen.isEmpty {
        print("PASS: \(tracePairingName)"); passed += 1
    } else {
        print("FAIL: \(tracePairingName)")
        if !trace.contains("Pid=") {
            print("      [no trace output at all -- did -d 0x0002 reach the emulator?]")
        }
        for u in unpaired    { print("      return printed with no entry: pid=\(u.0) \(u.1)") }
        for m in mismatched  { print("      pid=\(m.0) entered \(m.1) but return printed as \(m.2)") }
        for s in strayOpen   { print("      entry never returned: pid=\(s.0) \(s.1)") }
        failed += 1
    }
}

// ── Results ───────────────────────────────────────────────────────────────────

try? FileManager.default.removeItem(atPath: scratchDisk) // the run owns it; take it with us
// The canary outlives its own tests: container mode mounts it into EVERY
// invocation, so removing it when the fs block finished would leave every later
// test asking docker to mount a path that no longer exists.
try? FileManager.default.removeItem(atPath: canaryHost)

print("\nResults: \(passed) passed, \(failed) failed")
exit(failed > 0 ? 1 : 0)
