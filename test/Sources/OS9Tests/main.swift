// ── F$SUser enforces the TRM's three cases ───────────────────────────────────
// v2.4 TRM, F$SUser: "User number 0.0 may change their ID to anything without
// restriction. A primary module owned by user 0.0 may change its ID to anything
// without restriction. Any primary module may change its user ID to match the
// module's owner. All other attempts ... return an E$Permit error."
//
// Until this was enforced, F$SUser assigned from d1 and returned 0, so any
// guest program could become 0.0 at will -- and since is_super() (group 0) is
// the codebase's only privilege test, that bypassed the entire permission model
// from inside. Demonstrated live before the fix; see the roadmap entry it closed.
//
// Both cases below run as claude (1.7) executing a module claude linked, so
// `l68` stamps M$Owner 1.7 -- the SAME program and the SAME user, differing
// only in the identity requested. That is what makes the pair meaningful: one
// asserts the gate refuses, the other that it does not simply refuse everything.
// Running as 0.0 would make both vacuous via rule 1, the same trap that let the
// original bug sit undetected.
if !containerized {
    func suserSrc(_ wanted: String) -> String {
        ["Prgrm set 1", "Objct set 1", "ReEnt set $80",
         " psect sutst,(Prgrm<<8)+Objct,(ReEnt<<8)+1,0,200,start",
         "start",
         " move.l #\(wanted),d1",
         " trap #0", " dc.w $1C",          // F$SUser
         " bcs.s denied",
         " lea okmsg(pc),a0", " move.l #oklen,d1", " bra.s emit",
         "denied",
         " lea nomsg(pc),a0", " move.l #nolen,d1",
         "emit",
         " move.w #1,d0", " trap #0", " dc.w $8A",   // I$Write to stdout
         " moveq #0,d1", " trap #0", " dc.w $06",    // F$Exit
         "okmsg dc.b \"SUSER-ALLOWED\",13,10", "oklen equ *-okmsg",
         "nomsg dc.b \"SUSER-DENIED\",13,10", "nolen equ *-nomsg",
         " ends"].joined(separator: "\r") + "\r"     // OS-9 lines end in CR
    }

    func buildAndRun(_ tag: String, _ wanted: String) -> [String] {
        try? suserSrc(wanted).write(toFile: scratchDisk + "/\(tag).a",
                                    atomically: true, encoding: .utf8)
        return ["login claude", "chx /dd/CMDS",
                "r68 \(scratch)/\(tag).a -o=\(scratch)/\(tag).r",
                "l68 \(scratch)/\(tag).r -o=\(scratch)/\(tag)",
                "\(scratch)/\(tag)", "logout"]
    }

    // Rule 1 fails (1.7 is not 0.0), rule 2 fails (module owner is 1.7, not
    // 0.0), rule 3 fails (0.0 != the module's 1.7 owner) -> E$Permit.
    run("f$suser: an ordinary user cannot become 0.0 just by asking",
        expectation: "E$Permit -- none of the TRM's three cases apply",
        commands: buildAndRun("sudeny", "$00000000")) {
            $0.contains("SUSER-DENIED") && !$0.contains("SUSER-ALLOWED")
        }

    // Rule 3: the requested ID equals the primary module's own M$Owner (1.7).
    run("f$suser: a primary module may take on its own module's owner",
        expectation: "allowed -- TRM case 3, the ID matches M$Owner",
        commands: buildAndRun("suallow", "$00010007")) {
            $0.contains("SUSER-ALLOWED") && !$0.contains("SUSER-DENIED")
        }

    // Rule 2 is what keeps `login` working from an already-logged-in ordinary
    // user: login's own module is owned by 0.0, so it may set any identity.
    // Nothing else in the suite covers this -- a plain `login` from the stock
    // top-level shell is already 0.0 and so passes under rule 1 instead.
    run("f$suser: login still works from a non-0.0 shell (module owned by 0.0)",
        expectation: "nested login succeeds; rule 2 applies to login itself",
        commands: ["login claude", "login dog", "logout", "logout"]) {
            $0.contains("dog: ")
        }

    for leftover in ["sudeny.a", "sudeny.r", "sudeny",
                     "suallow.a", "suallow.r", "suallow"] {
        try? FileManager.default.removeItem(atPath: scratchDisk + "/" + leftover)
    }
}

// ── RBF EOF lock: a WRITE-only producer holds the end of the file ────────────
// v2.4 Technical Manual, ch.7 "End of File Lock": an EOF lock occurs when the
// user reads or writes data at the end of file, is kept "until a read or write
// is performed that is not at the end of the file", and "is the only time that
// a write call automatically causes lock out of any part of the file". The
// manual's own example is a spooler listing a file the assembler is still
// writing -- and an assembler redirecting output opened that file for
// SEQUENTIAL OUTPUT, not for update. So the lock cannot be gated on update
// mode, which is what os9exec used to do (it asked "is any update-mode path
// open for writing?" instead of "does anyone hold the end?").
//
// The shell's `>` is a write-only open, so this is the manual's example almost
// literally: a producer writes one line, waits, writes a second, closes; a
// read-only `list` starts in between. Passing means the reader waited at the
// edge rather than calling the gap end-of-file. Deliberately on a `mount -k`
// RBF image -- this lock lives in file_rbf.c and a host directory never
// reaches it.
if !containerized {
    let prod = ["echo EOFLK-one", "sleep 4", "echo EOFLK-two"]
        .joined(separator: "\r") + "\r"          // OS-9 lines end in CR
    try? prod.write(toFile: scratchDisk + "/prod", atomically: true, encoding: .utf8)

    run("rbf eof lock: a read-only reader follows a write-only producer",
        expectation: "list waits at end of file and returns both lines",
        commands: ["mount -k=360k h7",
                   "shell <\(scratch)/prod >/h7/spool &",
                   "sleep 1",
                   "list /h7/spool",
                   "sleep 3"],
        timeout: 60) {
            $0.contains("EOFLK-one") && $0.contains("EOFLK-two")
        }

    try? FileManager.default.removeItem(atPath: scratchDisk + "/prod")
}

// -- host-backed terminals -------------------------------------------------
// An unconfigured /tN is not a device. It used to silently alias the main
// console, so `echo` to it appeared to work while interleaving its bytes into
// the shell's own prompt -- and `tsmon /t1` failed with a misleading E_NOTRDY
// much later instead of an honest "no such unit" at open time.
check("hostterm: unconfigured /t1 is E_UNIT",
      contains: "Error #000:240 (E_UNIT)",
      "echo hello >/t1")

// The plan's own Step 1 test for this task ("checkEnv contains: 'opened'"
// against a real pty slave) turned out unable to fail either as written or
// with the redirect it was missing -- investigated live, not assumed:
//   1. Task 1's gate in pCopen only checks hostterm_configured (is OS9T1
//      SET?), never hostterm_open. With OS9T1 pointed at a real pty slave,
//      that gate already lets the open through today, straight to the
//      pre-existing /t1 fallback path -- so "does /t1 open without error"
//      already passes BEFORE this task's code exists, for any *configured*
//      OS9T1, valid or not. hostterm_open is not reachable from pCopen
//      until this task's Step 4 wires the call in.
//   2. Separately, the OS-9 shell echoes every input line onto its own
//      console before executing it (confirmed live: an unknown command's
//      literal text appears verbatim in the captured output even though it
//      never ran), so a "contains" check whose pattern is a substring of
//      the command text itself -- "opened" in "echo opened" -- is satisfied
//      by the echoed input alone and can never fail regardless of what /t1
//      does.
// The one behaviour this task actually introduces that a pre-Task-4 gate
// cannot already produce is REFUSAL of a host path that does not work --
// hostterm_open is the first code that ever tries the host open() and can
// say no. A nonexistent path is that discriminating case: today it
// "succeeds" (any configured value passes the old gate); after this task
// hostterm_open's open() genuinely fails and pCopen reports E_DEVBSY.
//
// The successful-open case (a real pty slave) is intentionally not
// duplicated here as an automated check: with output/input not wired until
// Tasks 3/4, nothing observes hostterm_open's success yet, so any such
// check is provably unable to fail at this task's boundary -- confirmed by
// testing it directly against the untouched stub. Task 3's own test already
// asserts a genuine byte-level success signal (output reaching the pty
// master), so that is where a real positive check belongs.
checkEnv("hostterm: /t1 refuses a host path that does not exist",
         contains: "Error #000:216 (E_PNNF)",
         env: ["OS9T1": "/hostterm-definitely-does-not-exist"],
         "echo x >/t1")

// Creates a pty pair. Returns (masterFD, slaveFD, slaveDeviceName). The TEST
// owns both ends, so it can drive /tN from outside the emulator with no
// parsing of emulator output. A pty slave is an ordinary tty device, so this
// exercises exactly the code path a real /dev/cu.usbserial-* will take.
//
// <slave> is deliberately returned OPEN, not closed here, and must stay open
// (close it only once the caller is done reading). Confirmed live, isolated
// from hostterm entirely with a bare pty and no os9exec involved: on macOS,
// once the LAST open reference to a pty's SLAVE closes, any output not yet
// read by the master is discarded -- even a reader already BLOCKED in read()
// before the write+close is woken with zero bytes, not the data. This is
// deterministic, not a scheduling race a fast enough reader could win. The
// emulator opens the slave BY NAME for the lifetime of one redirected
// command (e.g. `echo x >/t1` opens, writes and closes the path within that
// one command) and then closes ITS OWN reference -- if the test had already
// closed its own copy (as a first version of this helper did), that emulator
// close would be the LAST reference, and the discard would fire before the
// test ever got to read(). Holding a second reference open here keeps the
// refcount above zero for the whole test, so the emulator's own open/close
// cycle never triggers the discard -- exactly how a real attached `screen`
// session (which never closes its end) already avoids this in practice.
// Deliberately does NOT put the pty into raw mode itself. A pty's termios
// state is one struct shared by both ends -- tcsetattr on the master and on
// the slave act on the SAME state -- so if this helper called cfmakeraw()
// here too, that call would already have put the pty in raw mode before the
// emulator's own hostterm_raw() (which runs on the slave, later) ever got a
// chance to matter, and the 8-bit-transparency check below could never fail
// no matter what hostterm_raw() does. Confirmed live: with hostterm_raw()'s
// own flag-clearing temporarily disabled, the check still passed as long as
// this function set raw mode too. Leaving the pty in its default (cooked)
// state here makes hostterm_raw() the ONLY thing that can put it in raw
// mode, so the check actually exercises it.
func makePTY() -> (master: Int32, slave: Int32, name: String)? {
    var master: Int32 = 0
    var slaveFD: Int32 = 0
    guard openpty(&master, &slaveFD, nil, nil, nil) == 0 else { return nil }
    let name = String(cString: ttyname(slaveFD))
    _ = fcntl(master, F_SETFL, fcntl(master, F_GETFL, 0) | O_NONBLOCK)
    return (master, slaveFD, name)
}

// Reads everything currently available on <fd> without blocking.
func drainNonBlocking(_ fd: Int32) -> [UInt8] {
    var out = [UInt8]()
    var buf = [UInt8](repeating: 0, count: 4096)
    while true {
        let n = read(fd, &buf, buf.count)
        if n <= 0 { break }
        out.append(contentsOf: buf[0..<n])
    }
    return out
}

// Output path: bytes OS-9 writes to /t1 must reach the host endpoint, not the
// emulator's own stdout. Names checked against `filter` by hand -- this block
// doesn't go through run()/check(), so it has to opt itself out the same way
// they do, rather than paying for an emulator run on every unrelated filter.
let hostOutputName  = "hostterm: output reaches the host endpoint"
let hostRawModeName = "hostterm: raw mode passes control bytes through unmangled"
let runHostOutput   = filter.isEmpty || hostOutputName.localizedCaseInsensitiveContains(filter)
let runHostRawMode  = filter.isEmpty || hostRawModeName.localizedCaseInsensitiveContains(filter)

if runHostOutput || runHostRawMode {
    if let (master, slave, slaveName) = makePTY() {
        _ = os9(["echo host-terminal-works >/t1"], env: ["OS9T1": slaveName])
        usleep(200_000)
        let text = String(decoding: drainNonBlocking(master), as: UTF8.self)

        if runHostOutput {
            if text.contains("host-terminal-works") {
                print("PASS: \(hostOutputName)"); passed += 1
            } else {
                print("FAIL: \(hostOutputName)")
                print("      [pty master should have received the echoed text]")
                print("      got: \(text.debugDescription.prefix(200))")
                failed += 1
            }
        }

        // 0x11/0x13 are XON/XOFF, 0x7f is DEL, and 0x0a is a bare LF with no
        // preceding CR of its own. This is the assertion that would catch a
        // missing raw-mode setup in hostterm_raw -- but XON/XOFF/DEL turned
        // out NOT to discriminate for this OUTPUT direction: a pty isn't
        // real hardware, so the input-side flags (IXON, ISTRIP, ICANON) that
        // would eat/rewrite them on a real serial line are simply irrelevant
        // to bytes a process WRITES to its slave -- confirmed live, this
        // check still passed with hostterm_raw()'s own flag-clearing
        // disabled. The one OUTPUT-direction flag in the raw-mode recipe is
        // OPOST (c_oflag), which on a cooked pty rewrites a bare LF to CRLF
        // -- also confirmed live, isolated from hostterm, against a bare
        // pty with no termios changes on either end. So the bare LF is what
        // actually exercises hostterm_raw() here; the check asserts the
        // whole 4-byte sequence arrives EXACTLY as sent (contiguous, in
        // order), which a spurious inserted CR would break.
        //
        // NOT sent as literal bytes in the command text (as first tried):
        // that hung the whole run. KeyToBuffer() (utilstuff.c) applies
        // PD_XON/PD_XOFF flow control to the MAIN console's own command-line
        // input -- typing OS9T1's XOFF (0x13, the same default this device
        // also uses) sets mco->holdScreen and the console's input pump stops
        // consuming stdin entirely, with no later XON in the stream to clear
        // it. That is a property of console 0 reading its own command line,
        // unrelated to hostterm -- confirmed by reproducing the same hang
