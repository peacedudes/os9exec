        "  psect cpytst,(Prgrm<<8)+Objct,(ReEnt<<8)+0,1,512,start",
        "",
        "start:",
        "  OS9     F$ID",              // d0.w = own PID (F$CpyMem's cosmetic owner arg)
        "  move.w  d0,d2",
        "* stage 1: copy into the module's own buffer (dst is PC-relative) -- allowed",
        "  lea     src(pc),a0",
        "  lea     dst(pc),a1",
        "  moveq   #8,d1",
        "  move.w  d2,d0",
        "  OS9     F$CpyMem",
        "  bcs     s2",                // errored: skip the OK token
        "  lea     mown(pc),a0",
        "  moveq   #mownl,d1",
        "  moveq   #1,d0",
        "  OS9     I$WritLn",
        "s2:",
        "* stage 2: copy into a foreign in-arena address ($1000) -- must be refused",
        "  lea     src(pc),a0",
        "  move.l  #$1000,a1",
        "  moveq   #8,d1",
        "  move.w  d2,d0",
        "  OS9     F$CpyMem",
        "  bcc     done",             // carry clear = write allowed = gate failed
        "  lea     mfor(pc),a0",
        "  moveq   #mforl,d1",
        "  moveq   #1,d0",
        "  OS9     I$WritLn",
        "done:",
        "  moveq   #0,d1",
        "  OS9     F$Exit",
        "mown:  dc.b  \"CPYMEM OWN OK\",$0D",
        "mownl  equ   *-mown",
        "mfor:  dc.b  \"CPYMEM FOREIGN BLOCKED\",$0D",
        "mforl  equ   *-mfor",
        "src:   dc.b  \"ABCDEFGH\"",
        "dst:   dc.b  0,0,0,0,0,0,0,0",
        "",
        "  ends",
        ""
    ].joined(separator: "\r")

    let asmPath = scratchDisk + "/cpytst.a"
    try? cmAsm.write(toFile: asmPath, atomically: true, encoding: .utf8)

    let name = "f$cpymem: writes its own memory, refuses a foreign address"
    if filter.isEmpty || name.localizedCaseInsensitiveContains(filter) {
        let out = os9([
            "load /dd/CMDS/r68 /dd/CMDS/l68",
            "r68 /h5/cpytst.a -o=/h5/cpytst.r",
            "l68 /h5/cpytst.r -o=/h5/cpytst",
            "/h5/cpytst"
        ], timeout: 20)
        if out.contains("CPYMEM OWN OK") && out.contains("CPYMEM FOREIGN BLOCKED") {
            print("PASS: \(name)")
            passed += 1
        } else {
            print("FAIL: \(name)")
            print("      [own-memory write must succeed AND a foreign-address write must be refused]")
            let preview = out.split(separator: "\n")
                .filter { !$0.hasPrefix("#") && $0 != "$" && !$0.isEmpty }
                .prefix(8).joined(separator: " | ")
            print("      output: \(preview)")
            failed += 1
        }
    }

    for leftover in ["cpytst.a", "cpytst.r", "cpytst"] {
        try? FileManager.default.removeItem(atPath: scratchDisk + "/" + leftover)
    }
}

// ── F$Load error reporting: a damaged module must say HOW it is damaged ──────
// A load is asked about a file NAME, so "this isn't a module" and "this module
// is broken" used to collapse into one answer, E_FNA (214). Once the MODSYNC
// word matches, the file IS a module and the specific check that failed is
// known -- and 214 sends the reader to the file's attributes and owner for a
// fault that has nothing to do with either. The v2.4 TRM gives E$BMCRC/E$BMHP
// for F$VModul, which performs exactly this check, and says F$Load errors on
// "a module with a bad parity or CRC".
//
// Fixtures are built here from a real module so the corruption is the ONLY
// difference: one flipped bit in the body (CRC alone) and one in the header
// (parity). The unmodified copy is the control -- without it a "wrong error
// code" test would pass just as well on a module that never loads at all, and
// it is also what keeps this honest in a container, where a macOS bind mount
// can ignore the execute bit the fixtures are given (project memory
// docker-macos-bindmount-ignores-permissions): if that ever bites, every case
// collapses to E_FNA and the control fails first. Measured, not assumed --
// `make test-linux` runs all four green.
if let goodModule = FileManager.default.contents(atPath: diskPath + "/CMDS/list") {
    func plant(_ name: String, _ bytes: [UInt8]) {
        let path = scratchDisk + "/" + name
        // host-native devices carry the real execute bit, and load opens with
        // read+exec (mode 0x05) -- without 0o755 every case below fails E_FNA
        // for want of permission and the whole block passes for the wrong reason
        FileManager.default.createFile(atPath: path, contents: Data(bytes),
                                       attributes: [.posixPermissions: 0o755])
    }
    var body   = [UInt8](goodModule)
    var header = [UInt8](goodModule)
    body[200]  ^= 0x01   // past the 24-byte header: breaks the CRC only
    header[10] ^= 0x01   // inside the header: breaks header parity
    plant("m_good",   [UInt8](goodModule))
    plant("m_badcrc", body)
    plant("m_badpar", header)
    plant("m_notmod", [UInt8]("this is plainly not a module\r".utf8))

    run("modload: an untouched module still loads (control)",
        expectation: "the fixtures differ from this ONLY by the corrupted bit",
        commands: ["load \(scratch)/m_good"]) { !$0.contains("Error #") }

    check("modload: a bad module CRC reports E_BMCRC, not E_FNA",
        contains: "E_BMCRC", "load \(scratch)/m_badcrc")

    check("modload: bad module header parity reports E_BMHP, not E_FNA",
        contains: "E_BMHP", "load \(scratch)/m_badpar")

    // The other half of the same rule: a file that was never a module keeps the
    // old answer. On this emulator a host directory routinely holds .c/.bas/.txt
    // beside real modules, and reporting a CRC error for those would be worse
    // than uninformative -- E_FNA is the honest "you cannot execute this".
    check("modload: a file that is not a module at all still reports E_FNA",
        contains: "E_FNA", "load \(scratch)/m_notmod")

    for leftover in ["m_good", "m_badcrc", "m_badpar", "m_notmod"] {
        try? FileManager.default.removeItem(atPath: scratchDisk + "/" + leftover)
    }
}

// ── F$ID packs group in the HIGH word, not the high byte ─────────────────────
// The TRM: d1.l is the "current process group/user number ... all word values",
// and F$SUser, prepFork, the module header's M$Owner and `ident` all use that
// 16/16 form. F$ID alone used the 6809-ish group<<8|user, so F$ID -> F$SUser
// did not round-trip and anything storing the result structurally got garbage.
//
// Asserted through the damage it actually did rather than by reading a register:
// `l68` stamps M$Owner from F$ID, so a module linked by claude (1.7) came out
// owned by "0.259" ($0103 pushed into the user half). `ident` is Microware's own
// decoder, which makes it a fair judge here. It must ALSO be a non-0.0 user --
// as 0.0 both packings give 0 and the test would be vacuous, which is exactly
// why the existing corpus never caught this.
if !containerized {
    let idSrc = ["Prgrm set 1", "Objct set 1", "ReEnt set $80",
                 " psect idtst,(Prgrm<<8)+Objct,(ReEnt<<8)+1,0,200,start",
                 "start", " moveq #0,d1", " trap #0", " dc.w $06", " ends"]
        .joined(separator: "\r") + "\r"          // OS-9 lines end in CR
    try? idSrc.write(toFile: scratchDisk + "/idtst.a", atomically: true, encoding: .utf8)

    run("f$id: a module linked by claude is stamped 1.7, not 0.259",
        expectation: "ident reports the builder's real group.user in M$Owner",
        commands: ["login claude", "chx /dd/CMDS",
                   "r68 \(scratch)/idtst.a -o=\(scratch)/idtst.r",
                   "l68 \(scratch)/idtst.r -o=\(scratch)/idtst",
                   "ident \(scratch)/idtst", "logout"]) {
            $0.contains("Owner:") && $0.contains("1.7") && !$0.contains("0.259")
        }

    for leftover in ["idtst.a", "idtst.r", "idtst"] {
        try? FileManager.default.removeItem(atPath: scratchDisk + "/" + leftover)
    }
}

